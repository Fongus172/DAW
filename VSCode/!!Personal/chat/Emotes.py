def get_emote_file(token: str) -> str | None:
    return EMOTE_MAP.get(token)

def get_emote_path(token: str) -> Path | None:
    filename = get_emote_file(token)
    if not filename:
        return None
    path = EMOTES_DIR / filename
    return path if path.exists() else None

def is_emote(token: str) -> bool:
    return get_emote_path(token) is not None